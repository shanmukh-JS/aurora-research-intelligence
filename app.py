# 13. FORMAT INTELLIGENCE FOR DISPLAY
# ================================================================
#
# Converts structured intelligence into readable Markdown.
# ================================================================

def format_intelligence_section(
    title,
    section_data
):
    """
    Format one intelligence section.
    """

    if not section_data:

        return (
            f"## {title}\n\n"
            "No information available."
        )


    items = section_data.get(
        "items",
        []
    )


    status = section_data.get(
        "status",
        "NOT_FOUND"
    )


    output = [

        f"## {title}",

        f"**Status:** `{status}`",

        ""

    ]


    if not items:

        output.append(
            "No supported information found."
        )

        return "\n".join(
            output
        )


    for index, item in enumerate(
        items,
        start=1
    ):

        statement = item.get(
            "statement",
            ""
        )

        item_status = item.get(
            "status",
            "NOT_FOUND"
        )

        category = item.get(
            "category"
        )


        output.append(
            f"### {index}. {statement}"
        )


        output.append(
            f"**Evidence status:** `{item_status}`"
        )


        if category:

            output.append(
                f"**Category:** {category}"
            )


        evidence = item.get(
            "evidence",
            []
        )


        if evidence:

            output.append(
                "**Evidence:**"
            )


            for evidence_record in evidence[:5]:

                page = evidence_record.get(
                    "page_number",
                    "?"
                )

                evidence_id = evidence_record.get(
                    "evidence_id",
                    "UNKNOWN"
                )


                output.append(
                    f"- Page {page} — "
                    f"`{evidence_id}`"
                )


        output.append("")


    return "\n".join(
        output
    )


