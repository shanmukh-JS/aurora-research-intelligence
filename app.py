# ================================================================
# 2. PDF CONFIGURATION
# ================================================================

# Maximum number of characters allowed in a single page
# before applying safe text normalization.
#
# This is intentionally large because research papers can
# contain long pages.
MAX_PAGE_TEXT_LENGTH = 100_000

# Minimum number of non-whitespace characters required for
# a page to be considered readable.
MIN_READABLE_CHARACTERS = 10

# Every uploaded paper receives a source ID.
SOURCE_ID_PREFIX = "AURORA-PAPER"


# ================================================================
# 3. TEXT CLEANING FUNCTION
# ================================================================
#
# PDF extraction sometimes creates:
# - excessive blank lines
# - repeated spaces
# - strange control characters
# - trailing whitespace
#
# We clean these carefully while preserving:
# - headings
# - paragraphs
# - sentences
# - numbers
# - symbols
# - useful line breaks
# ================================================================

def clean_pdf_text(text):
    """
    Clean text extracted from a PDF.

    The function keeps the original meaning and structure
    as much as possible.

    Parameters
    ----------
    text : str
        Raw text extracted from one PDF page.

    Returns
    -------
    str
        Cleaned page text.
    """

    # Handle an empty or invalid value safely.
    if not text:
        return ""

    # Convert the value to a string.
    text = str(text)

    # Replace null/control characters that sometimes appear
    # in PDF extraction.
    text = text.replace("\x00", " ")

    # Normalize Windows and old-style line endings.
    text = text.replace("\r\n", "\n")
    text = text.replace("\r", "\n")

    # Remove excessive spaces and tabs inside lines.
    cleaned_lines = []

    for line in text.split("\n"):

        # Replace tabs with spaces.
        line = line.replace("\t", " ")

        # Collapse repeated spaces.
        line = re.sub(r"[ ]{2,}", " ", line)

        # Remove spaces from the beginning/end of a line.
        line = line.strip()

        # Keep non-empty lines.
        if line:
            cleaned_lines.append(line)

    # Rebuild the page while preserving paragraph-like
    # line separation.
    text = "\n".join(cleaned_lines)

    # Prevent extremely large accidental page strings.
    if len(text) > MAX_PAGE_TEXT_LENGTH:

        text = text[:MAX_PAGE_TEXT_LENGTH].rstrip()

    return text


# ================================================================
# 4. PDF VALIDATION FUNCTION
# ================================================================
#
# We validate both:
#   1. File extension
#   2. Actual PDF structure
#
# This prevents files such as .txt or .htm renamed to .pdf
# from being accepted accidentally.
# ================================================================

def validate_pdf_file(file_path):
    """
    Validate that the supplied file is a readable PDF.

    Parameters
    ----------
    file_path : str
        Path of the uploaded file.

    Returns
    -------
    tuple
        (True, message) if valid.
        (False, message) if invalid.
    """

    # Check that a file was supplied.
    if not file_path:

        return (
            False,
            "No PDF file was provided."
        )

    # Convert to string in case a compatible file object
    # supplies the path as another type.
    file_path = str(file_path)

    # Check file extension.
    if not file_path.lower().endswith(".pdf"):

        return (
            False,
            "Invalid file type. Please upload a PDF file."
        )

    # Check whether the file actually exists.
    if not os.path.isfile(file_path):

        return (
            False,
            "The uploaded PDF file could not be found."
        )

    # Check that the file is not empty.
    file_size = os.path.getsize(file_path)

    if file_size == 0:

        return (
            False,
            "The uploaded PDF is empty."
        )

    # Check the PDF signature.
    #
    # A valid PDF normally begins with:
    # %PDF-
    try:

        with open(file_path, "rb") as file:

            header = file.read(5)

        if header != b"%PDF-":

            return (
                False,
                "The file has a PDF extension but is not a valid PDF."
            )

    except Exception as error:

        return (
            False,
            f"Could not inspect the uploaded file: {error}"
        )

    return (
        True,
        "PDF validation successful."
    )


# ================================================================
# 5. CREATE A SOURCE ID
# ================================================================
#
# Each paper gets a stable source ID.
#
# Example:
#     AURORA-PAPER-001
#
# Page evidence then becomes:
#
#     AURORA-PAPER-001-PAGE-001
#     AURORA-PAPER-001-PAGE-002
#     AURORA-PAPER-001-PAGE-003
# ================================================================

def create_source_id():

    # Count how many papers have previously been loaded
    # during this notebook session.
    existing_source_id = AURORA["paper"].get("source_id")

    if existing_source_id:

        # Extract the previous numeric identifier.
        match = re.search(
            r"(\d+)$",
            existing_source_id
        )

        if match:

            next_number = int(match.group(1)) + 1

        else:

            next_number = 1

    else:

        next_number = 1

    return f"{SOURCE_ID_PREFIX}-{next_number:03d}"


# ================================================================
# 6. EXTRACT PDF INFORMATION
# ================================================================
#
# This is the main PDF ingestion function.
#
# It:
#   - validates the file
#   - opens the PDF
#   - reads every page
#   - cleans the text
#   - creates evidence IDs
#   - stores everything in AURORA
# ================================================================

def extract_research_paper(pdf_input):
    """
    Extract a research paper page-by-page.

    Parameters
    ----------
    pdf_input : str or compatible file object
        Uploaded PDF path.

    Returns
    -------
    dict
        Complete extraction result.
    """

    # ------------------------------------------------------------
    # HANDLE MISSING FILE
    # ------------------------------------------------------------

    if pdf_input is None:

        return {
            "success": False,
            "message": "Please upload a PDF file first.",
            "data": None
        }


    # ------------------------------------------------------------
    # GET FILE PATH
    # ------------------------------------------------------------
    #
    # Depending on the Gradio version or how the function
    # is called, the input may be:
    #
    #   - a string path
    #   - an object containing .name
    #   - an object containing .path
    #
    # We support all three safely.
    # ------------------------------------------------------------

    file_path = None

    if isinstance(pdf_input, str):

        file_path = pdf_input

    elif hasattr(pdf_input, "path"):

        file_path = pdf_input.path

    elif hasattr(pdf_input, "name"):

        file_path = pdf_input.name

    else:

        file_path = str(pdf_input)


    # ------------------------------------------------------------
    # VALIDATE THE PDF
    # ------------------------------------------------------------

    is_valid, validation_message = validate_pdf_file(
        file_path
    )

    if not is_valid:

        return {
            "success": False,
            "message": validation_message,
            "data": None
        }


    # ------------------------------------------------------------
    # CREATE SOURCE ID
    # ------------------------------------------------------------

    source_id = create_source_id()


    # ------------------------------------------------------------
    # OPEN PDF
    # ------------------------------------------------------------

    document = None

    try:

        document = pymupdf.open(file_path)

    except Exception as error:

        return {
            "success": False,
            "message": (
                "The PDF could not be opened. "
                f"Reason: {error}"
            ),
            "data": None
        }


    # ------------------------------------------------------------
    # BASIC PDF INFORMATION
    # ------------------------------------------------------------

    page_count = len(document)

    if page_count == 0:

        document.close()

        return {
            "success": False,
            "message": "The PDF contains no pages.",
            "data": None
        }


    # ------------------------------------------------------------
    # EXTRACT EVERY PAGE
    # ------------------------------------------------------------

    pages = []

    total_characters = 0
    total_words = 0

    readable_pages = 0
    empty_pages = []

    extraction_errors = []


    for page_index in range(page_count):

        # Human-readable page number starts from 1.
        page_number = page_index + 1

        # Evidence ID uniquely identifies this page.
        evidence_id = (
            f"{source_id}-PAGE-{page_number:03d}"
        )

        try:

            # Get the PDF page.
            page = document[page_index]

            # Extract normal text from the page.
            raw_text = page.get_text("text")

            # Clean the extracted text.
            cleaned_text = clean_pdf_text(raw_text)

            # Count characters and words.
            character_count = len(cleaned_text)

            word_count = len(
                re.findall(
                    r"\S+",
                    cleaned_text
                )
            )

            # Determine whether the page contains usable text.
            is_readable = (
                character_count >= MIN_READABLE_CHARACTERS
            )

            if is_readable:

                readable_pages += 1

            else:

                empty_pages.append(page_number)


            # Store complete page-level evidence.
            page_record = {

                "page_number": page_number,

                "evidence_id": evidence_id,

                "source_id": source_id,

                "text": cleaned_text,

                "raw_character_count": len(raw_text),

                "character_count": character_count,

                "word_count": word_count,

                "readable": is_readable

            }

            pages.append(page_record)

            total_characters += character_count
            total_words += word_count

        except Exception as error:

            # Keep processing the remaining pages even if
            # one individual page causes an extraction issue.
            extraction_errors.append(
                {
                    "page_number": page_number,
                    "error": str(error)
                }
            )

            pages.append(
                {
                    "page_number": page_number,
                    "evidence_id": evidence_id,
                    "source_id": source_id,
                    "text": "",
                    "raw_character_count": 0,
                    "character_count": 0,
                    "word_count": 0,
                    "readable": False,
                    "error": str(error)
                }
            )

            empty_pages.append(page_number)


    # ------------------------------------------------------------
    # CLOSE PDF
    # ------------------------------------------------------------

    document.close()


    # ------------------------------------------------------------
    # FILE INFORMATION
    # ------------------------------------------------------------

    file_name = os.path.basename(file_path)

    file_size_bytes = os.path.getsize(file_path)

    file_size_mb = round(
        file_size_bytes / (1024 * 1024),
        2
    )


    # ------------------------------------------------------------
    # UPDATE AURORA STATE
    # ------------------------------------------------------------

    AURORA["paper"] = {

        "file_name": file_name,

        "file_path": file_path,

        "source_id": source_id,

        "title": None,

        "authors": [],

        "page_count": page_count,

        "word_count": total_words,

        "character_count": total_characters,

        "file_size_bytes": file_size_bytes,

        "file_size_mb": file_size_mb,

        "readable_pages": readable_pages,

        "empty_pages": empty_pages,

        "extraction_errors": extraction_errors

    }


    # Store page-level evidence.
    AURORA["pages"] = pages


    # Update application status.
    AURORA["status"]["pdf_uploaded"] = True

    AURORA["status"]["pdf_extracted"] = (
        len(pages) == page_count
        and len(extraction_errors) == 0
    )


    # ------------------------------------------------------------
    # CREATE EXTRACTION RESULT
    # ------------------------------------------------------------

    result = {

        "success": True,

        "message": "PDF extracted successfully.",

        "data": {

            "file_name": file_name,

            "source_id": source_id,

            "page_count": page_count,

            "readable_pages": readable_pages,

            "empty_pages": empty_pages,

            "word_count": total_words,

            "character_count": total_characters,

            "file_size_mb": file_size_mb,

            "extraction_errors": extraction_errors,

            "pages": pages

        }

    }

    return result


# ================================================================
# 7. CREATE A SIMPLE EXTRACTION REPORT
# ================================================================
#
# This function converts the extraction result into a
# clean human-readable report.
#
# The full page text remains safely stored in AURORA.
# ================================================================

def create_extraction_report(result):
    """
    Create a readable extraction report.
    """

    if not result["success"]:

        return (
            "## ❌ PDF Extraction Failed\n\n"
            f"{result['message']}"
        )


    data = result["data"]

    file_name = data["file_name"]

    source_id = data["source_id"]

    page_count = data["page_count"]

    readable_pages = data["readable_pages"]

    empty_pages = data["empty_pages"]

    word_count = data["word_count"]

    character_count = data["character_count"]

    file_size_mb = data["file_size_mb"]

    errors = data["extraction_errors"]


    # ------------------------------------------------------------
    # BASIC REPORT
    # ------------------------------------------------------------

    report = f"""
# ✅ PDF Extraction Successful

### Paper Information

| Property | Value |
|---|---|
| **File** | `{file_name}` |
| **Source ID** | `{source_id}` |
| **Pages** | `{page_count}` |
| **Readable Pages** | `{readable_pages}` |
| **Words** | `{word_count:,}` |
| **Characters** | `{character_count:,}` |
| **File Size** | `{file_size_mb} MB` |

### Evidence System

Every page has received a unique evidence ID.

Example:

`{source_id}-PAGE-001`

`{source_id}-PAGE-002`

`{source_id}-PAGE-003`
"""


    # ------------------------------------------------------------
    # EMPTY PAGE INFORMATION
    # ------------------------------------------------------------

    if empty_pages:

        page_list = ", ".join(
            str(page)
            for page in empty_pages
        )

        report += f"""

### ⚠️ Pages With Little or No Extractable Text

Pages:

`{page_list}`

These pages may contain scanned images or text that
cannot be extracted normally. We will handle this
carefully in later versions if required.
"""

    else:

        report += """

### ✅ Page Extraction

All pages contained extractable text.
"""


    # ------------------------------------------------------------
    # EXTRACTION ERRORS
    # ------------------------------------------------------------

    if errors:

        report += f"""

### ⚠️ Extraction Warnings

Number of affected pages:

`{len(errors)}`
"""

    else:

        report += """

### ✅ Extraction Errors

No page-level extraction errors detected.
"""


    report += """

---

### AURORA Status

**PDF uploaded:** ✅

**Page extraction:** ✅

**Evidence mapping:** ✅

**Gemini calls used:** 0

**Ready for Cell 3:** ✅
"""


    return report


