#
# We use AST where possible to remove calls such as:
#
#     AURORA_APP.launch(...)
#
# ------------------------------------------------------------

def remove_launch_calls(source_code):

    try:
        tree = ast.parse(source_code)
    except SyntaxError:
        # If AST parsing fails, keep the source for now.
        # The validation step below will report the issue.
        return source_code

    class LaunchCallRemover(ast.NodeTransformer):

        def visit_Expr(self, node):

            # Detect:
            #
            # AURORA_APP.launch(...)
            #
            if isinstance(node.value, ast.Call):

                func = node.value.func

                if (
                    isinstance(func, ast.Attribute)
                    and func.attr == "launch"
                ):
                    return None

            return self.generic_visit(node)

        def visit_If(self, node):

            # Remove notebook production entry blocks such as:
            #
            # if __name__ == "__main__":
            #
            # if they already contain a launch call.
            #
            if (
                isinstance(node.test, ast.Compare)
                and isinstance(node.test.left, ast.Name)
                and node.test.left.id == "__name__"
            ):
                try:
                    source_segment = ast.get_source_segment(
                        source_code,
                        node
                    )

                    if source_segment and ".launch" in source_segment:
                        return None

                except Exception:
                    pass

            return self.generic_visit(node)

    tree = LaunchCallRemover().visit(tree)
    ast.fix_missing_locations(tree)

    try:
        return ast.unparse(tree)
    except Exception:
        return source_code


