# 6. FIND PAGE BY KEYWORD
# ================================================================
#
# Local analysis helper.
#
# It searches the extracted paper without using Gemini.
# ================================================================

def find_pages_containing(keywords):

    pages = get_extracted_pages()

    if not pages:

        return []

    if isinstance(keywords, str):

        keywords = [keywords]

    keywords = [
        str(keyword).lower()
        for keyword in keywords
    ]

    matches = []

    for page in pages:

        text = page.get("text", "")

        lower_text = text.lower()

        if any(
            keyword in lower_text
            for keyword in keywords
        ):

            matches.append(page)

    return matches


