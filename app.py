# 14. BUILD LOCAL FALLBACK ANALYSIS
# ================================================================
#
# If Gemini is unavailable, AURORA still produces a useful
# evidence-aware analysis using the extracted paper.
#
# IMPORTANT:
# It does NOT pretend that missing information exists.
# ================================================================

def build_local_analysis():

    analysis = create_empty_analysis()


    # ------------------------------------------------------------
    # TITLE
    # ------------------------------------------------------------

    title, evidence = local_extract_title()

    if title:

        analysis["title"] = {

            "value": title,

            "status": "PAPER_EVIDENCE_CANDIDATE",

            "evidence": evidence

        }


    # ------------------------------------------------------------
    # AUTHORS
    # ------------------------------------------------------------

    authors, evidence = local_extract_authors()

    if authors:

        analysis["authors"] = {

            "value": authors,

            "status": "PAPER_EVIDENCE_CANDIDATE",

            "evidence": evidence

        }


    # ------------------------------------------------------------
    # ABSTRACT
    # ------------------------------------------------------------

    abstract, evidence = local_extract_abstract()

    if abstract:

        analysis["abstract"] = {

            "value": abstract,

            "status": "PAPER_STATED",

            "evidence": evidence

        }


    # ------------------------------------------------------------
    # KEYWORDS
    # ------------------------------------------------------------

    keywords, evidence = local_extract_keywords()

    if keywords:

        analysis["keywords"] = {

            "value": keywords,

            "status": "PAPER_STATED",

            "evidence": evidence

        }


    # ------------------------------------------------------------
    # OTHER SECTIONS
    # ------------------------------------------------------------

    for field_name in SECTION_KEYWORDS:

        if field_name in [
            "title",
            "authors",
            "abstract",
            "keywords"
        ]:

            continue

        evidence = local_find_section_evidence(
            field_name
        )

        if evidence:

            analysis[field_name] = {

                "value": (
                    "Relevant paper evidence detected. "
                    "Semantic analysis requires AI interpretation."
                ),

                "status": "PAPER_EVIDENCE_CANDIDATE",

                "evidence": evidence

            }


    return analysis


