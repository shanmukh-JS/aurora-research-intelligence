def local_find_section_evidence(field_name):

    keywords = SECTION_KEYWORDS.get(
        field_name,
        []
    )

    matching_pages = find_pages_containing(
        keywords
    )

    evidence = []

    for page in matching_pages[:3]:

        text = page_text(page)

        # Keep the excerpt limited.
        excerpt = text[:1000]

        evidence.append(
            make_evidence_record(
                page,
                section=field_name,
                excerpt=excerpt
            )
        )

    return evidence


