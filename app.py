# 7. CREATE EVIDENCE RECORD
# ================================================================
#
# This creates a consistent evidence object.
# ================================================================

def make_evidence_record(
    page,
    section="",
    excerpt=""
):

    if not page:

        return None

    return {

        "source_id": page.get("source_id"),

        "evidence_id": page.get("evidence_id"),

        "page_number": page.get("page_number"),

        "section": section,

        "excerpt": excerpt[:1000]

    }


# ================================================================
# 8. EXTRACT TEXT FROM A PAGE
# ================================================================

def page_text(page):

    if not isinstance(page, dict):

        return ""

    return normalize_analysis_text(
        page.get("text", "")
    )


# ================================================================
# 9. EXTRACT TITLE LOCALLY
# ================================================================
#
# This is a fallback.
#
# The first page normally contains the title, so we inspect
# the beginning of page 1.
# ================================================================

def local_extract_title():

    pages = get_extracted_pages()

    if not pages:

        return None, []

    first_page = pages[0]

    text = first_page.get("text", "")

    if not text:

        return None, []

    lines = [
        line.strip()
        for line in text.split("\n")
        if line.strip()
    ]

    # Ignore extremely long lines because they are unlikely
    # to be a paper title.
    candidates = []

    for line in lines[:20]:

        if len(line) < 15:

            continue

        if len(line) > 300:

            continue

        lower_line = line.lower()

        # Avoid common metadata labels.
        ignored = [
            "abstract",
            "keywords",
            "index terms",
            "received",
            "accepted",
            "published"
        ]

        if lower_line in ignored:

            continue

        candidates.append(line)

    if not candidates:

        return None, []

    title = candidates[0]

    evidence = [
        make_evidence_record(
            first_page,
            section="Title",
            excerpt=title
        )
    ]

    return title, evidence


# ================================================================
# 10. EXTRACT AUTHORS LOCALLY
# ================================================================
#
# This is deliberately conservative.
#
# If authors cannot be identified confidently,
# the system returns NOT_FOUND rather than inventing names.
# ================================================================

def local_extract_authors():

    pages = get_extracted_pages()

    if not pages:

        return [], []

    first_page = pages[0]

    text = first_page.get("text", "")

    if not text:

        return [], []

    lines = [
        line.strip()
        for line in text.split("\n")
        if line.strip()
    ]

    author_candidates = []

    # Search only near the beginning of the first page.
    for index, line in enumerate(lines[:25]):

        lower_line = line.lower()

        # Strong indicators that the following text may contain
        # author information.
        if (
            "author" in lower_line
            or "authors" in lower_line
        ):

            candidate_lines = lines[
                index + 1:index + 4
            ]

            for candidate in candidate_lines:

                if (
                    2 <= len(candidate.split()) <= 12
                    and len(candidate) < 200
                ):

                    author_candidates.append(candidate)

            break

    # If no explicit author label was found, use a conservative
    # pattern for common academic name formatting.
    if not author_candidates:

        for line in lines[1:12]:

            if (
                2 <= len(line.split()) <= 8
                and len(line) < 150
                and not any(
                    symbol in line
                    for symbol in ["@", "http", "www."]
                )
            ):

                # Avoid obvious title/metadata lines.
                lower_line = line.lower()

                blocked = [
                    "abstract",
                    "keywords",
                    "index terms",
                    "university",
                    "department",
                    "college",
                    "received",
                    "accepted"
                ]

                if not any(
                    word in lower_line
                    for word in blocked
                ):

                    author_candidates.append(line)

                    if len(author_candidates) >= 3:

                        break

    # Remove duplicates while preserving order.
    unique_authors = []

    for author in author_candidates:

        if author not in unique_authors:

            unique_authors.append(author)

    if not unique_authors:

        return [], []

    evidence = [
        make_evidence_record(
            first_page,
            section="Authors",
            excerpt="; ".join(unique_authors)
        )
    ]

    return unique_authors, evidence


# ================================================================
# 11. EXTRACT ABSTRACT LOCALLY
# ================================================================
#
# Searches for an explicit "Abstract" section.
# ================================================================

def local_extract_abstract():

    pages = get_extracted_pages()

    for page in pages:

        text = page_text(page)

        if not text:

            continue

        # Find the abstract heading.
        match = re.search(
            r"\babstract\b\s*[:\-]?\s*(.*)",
            text,
            flags=re.IGNORECASE | re.DOTALL
        )

        if not match:

            continue

        abstract_text = match.group(1).strip()

        # Stop at common next sections.
        stop_patterns = [
            r"\bkeywords?\b",
            r"\bindex terms?\b",
            r"\bintroduction\b",
            r"\b1\.\s*introduction\b"
        ]

        for pattern in stop_patterns:

            stop_match = re.search(
                pattern,
                abstract_text,
                flags=re.IGNORECASE
            )

            if stop_match:

                abstract_text = (
                    abstract_text[
                        :stop_match.start()
                    ].strip()
                )

                break

        if len(abstract_text) >= 30:

            evidence = [
                make_evidence_record(
                    page,
                    section="Abstract",
                    excerpt=abstract_text
                )
            ]

            return abstract_text, evidence

    return None, []


