# 4. NORMALIZE TEXT FOR SEARCH
# ================================================================
#
# Used by the local fallback extractor.
# ================================================================

def normalize_analysis_text(text):

    if not text:

        return ""

    text = str(text)

    text = text.replace("\x00", " ")

    text = re.sub(
        r"[ \t]+",
        " ",
        text
    )

    return text.strip()


