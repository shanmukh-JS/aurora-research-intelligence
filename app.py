# 17. NORMALIZE GEMINI ANALYSIS
# ================================================================
#
# This ensures that Gemini cannot break the AURORA data structure
# by omitting fields.
# ================================================================

def normalize_analysis(gemini_analysis):

    normalized = create_empty_analysis()


    if not isinstance(
        gemini_analysis,
        dict
    ):

        return normalized


    for field_name in ANALYSIS_FIELDS:

        field_data = gemini_analysis.get(
            field_name
        )


        if not isinstance(
            field_data,
            dict
        ):

            continue


        value = field_data.get(
            "value"
        )

        status = field_data.get(
            "status",
            "NOT_FOUND"
        )

        evidence = field_data.get(
            "evidence",
            []
        )


        # Only accept known evidence statuses.
        valid_statuses = {

            "PAPER_STATED",

            "PAPER_EVIDENCE_CANDIDATE",

            "NOT_FOUND",

            "AI_INFERRED",

            "POTENTIAL_GAP_REQUIRES_REVIEW"

        }

        if status not in valid_statuses:

            status = "PAPER_EVIDENCE_CANDIDATE"


        if not isinstance(
            evidence,
            list
        ):

            evidence = []


        normalized[field_name] = {

            "value": value,

            "status": status,

            "evidence": evidence

        }


    return normalized


