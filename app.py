# ================================================================
# 4. TOKENIZATION FUNCTION
# ================================================================
#
# Converts text into normalized search terms.
#
# Example:
#
# "Explain the drug recommendation model"
#
# becomes approximately:
#
# ["explain", "drug", "recommendation", "model"]
# ================================================================

def rag_tokenize(text):
    """
    Convert text into normalized lexical retrieval tokens.

    Parameters
    ----------
    text : str
        Text to tokenize.

    Returns
    -------
    list
        Cleaned tokens.
    """

    if not text:

        return []

    # Convert to lowercase.
    text = str(text).lower()

    # Keep letters, numbers and meaningful hyphenated terms.
    text = re.sub(
        r"[^a-z0-9\-\s]",
        " ",
        text
    )

    # Split into individual terms.
    tokens = text.split()

    # Remove very short terms and common stop words.
    tokens = [

        token

        for token in tokens

        if (
            len(token) >= 2
            and token not in RAG_STOP_WORDS
        )

    ]

    return tokens


# ================================================================
# 5. NORMALIZE SEARCH TEXT
# ================================================================

def rag_normalize_text(text):
    """
    Normalize text for retrieval and phrase matching.
    """

    if not text:

        return ""

    text = str(text).lower()

    text = re.sub(
        r"\s+",
        " ",
        text
    )

    return text.strip()


# ================================================================
# 6. SPLIT TEXT INTO CHUNKS
# ================================================================
#
# Each page is divided into manageable overlapping chunks.
#
# Example:
#
# PAGE 5
#   ├── Chunk 1
#   ├── Chunk 2
#   ├── Chunk 3
#   └── ...
#
# Overlap helps prevent important information from being
# lost when a sentence falls between two chunks.
# ================================================================

def split_text_into_chunks(
    text,
    chunk_size=RAG_CHUNK_SIZE,
    overlap=RAG_CHUNK_OVERLAP
):
    """
    Split text into overlapping chunks.

    Parameters
    ----------
    text : str
        Source text.

    chunk_size : int
        Maximum approximate chunk size.

    overlap : int
        Number of overlapping characters.

    Returns
    -------
    list
        Text chunks.
    """

    if not text:

        return []

    text = str(text).strip()

    if not text:

        return []

    # Protect against invalid configuration.
    if chunk_size <= 0:

        raise ValueError(
            "RAG chunk size must be greater than zero."
        )

    if overlap < 0:

        raise ValueError(
            "RAG chunk overlap cannot be negative."
        )

    if overlap >= chunk_size:

        raise ValueError(
            "RAG chunk overlap must be smaller than "
            "the chunk size."
        )


    # ------------------------------------------------------------
    # SHORT TEXT
    # ------------------------------------------------------------

    if len(text) <= chunk_size:

        return [text]


    chunks = []

    start = 0

    text_length = len(text)


    # ------------------------------------------------------------
    # CREATE OVERLAPPING CHUNKS
    # ------------------------------------------------------------

    while start < text_length:

        end = min(
            start + chunk_size,
            text_length
        )

        chunk = text[start:end].strip()

        if chunk:

            chunks.append(chunk)

        # Stop once the end of the text is reached.
        if end >= text_length:

            break

        # Move forward while retaining overlap.
        start = end - overlap


    return chunks


# ================================================================
# 7. CREATE RAG CHUNK RECORD
# ================================================================
#
# Each chunk stores both searchable text and evidence metadata.
# ================================================================

def create_rag_chunk(
    source_id,
    page_number,
    evidence_id,
    chunk_number,
    text
):
    """
    Create one structured RAG chunk.
    """

    tokens = rag_tokenize(text)

    token_set = set(tokens)

    normalized_text = rag_normalize_text(text)

    return {

        "chunk_id": (
            f"{source_id}-PAGE-"
            f"{page_number:03d}-"
            f"CHUNK-{chunk_number:03d}"
        ),

        "source_id": source_id,

        "page_number": page_number,

        "evidence_id": evidence_id,

        "chunk_number": chunk_number,

        "text": text,

        "normalized_text": normalized_text,

        "tokens": tokens,

        "token_set": token_set,

        "character_count": len(text),

        "word_count": len(
            re.findall(
                r"\S+",
                text
            )
        )

    }


