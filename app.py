# 5. VALIDATE Q&A CITATIONS
# ================================================================
#
# Gemini is not allowed to invent citations.
#
# We compare returned citations with the evidence actually
# retrieved from the RAG system.
# ================================================================

def validate_qa_citations(
    qa_data,
    retrieval_results
):
    """
    Validate citations against retrieved evidence.
    """

    if not isinstance(
        qa_data,
        dict
    ):

        return None


    results = retrieval_results.get(
        "results",
        []
    )


    # Build sets of valid evidence identifiers.
    valid_evidence_ids = {

        result.get(
            "evidence_id"
        )

        for result in results

        if result.get(
            "evidence_id"
        )

    }


    valid_pages = {

        result.get(
            "page_number"
        )

        for result in results

        if result.get(
            "page_number"
        ) is not None

    }


    citations = qa_data.get(
        "citations",
        []
    )


    if not isinstance(
        citations,
        list
    ):

        citations = []


    validated_citations = []


    for citation in citations:

        if not isinstance(
            citation,
            dict
        ):

            continue


        evidence_id = citation.get(
            "evidence_id"
        )

        page = citation.get(
            "page"
        )


        # Accept the citation only if it refers to evidence
        # that was actually retrieved.
        evidence_valid = (
            evidence_id in valid_evidence_ids
        )

        page_valid = (
            page in valid_pages
        )


        if evidence_valid or page_valid:

            validated_citations.append(
                citation
            )


    qa_data["citations"] = (
        validated_citations
    )


    return qa_data


