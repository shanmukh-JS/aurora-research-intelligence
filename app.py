def validate_analysis_evidence(analysis):

    valid_evidence_ids = {

        page.get("evidence_id")

        for page in get_extracted_pages()

        if page.get("evidence_id")

    }


    valid_page_numbers = {

        page.get("page_number")

        for page in get_extracted_pages()

    }


    for field_name in ANALYSIS_FIELDS:

        field = analysis.get(
            field_name,
            {}
        )

        evidence_list = field.get(
            "evidence",
            []
        )

        valid_records = []


        for evidence in evidence_list:

            if not isinstance(
                evidence,
                dict
            ):

                continue


            evidence_id = evidence.get(
                "evidence_id"
            )

            page_number = evidence.get(
                "page_number"
            )


            # Keep evidence only if it maps to an actual
            # extracted page.
            if (
                evidence_id in valid_evidence_ids
                or page_number in valid_page_numbers
            ):

                valid_records.append(
                    evidence
                )


        field["evidence"] = valid_records


    return analysis


