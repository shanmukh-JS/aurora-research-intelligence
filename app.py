# ================================================================
# 4. PARSE GEMINI Q&A RESPONSE
# ================================================================
#
# Gemini may occasionally return JSON inside Markdown fences.
# This function handles both formats.
# ================================================================

def parse_qa_response(response_text):
    """
    Safely convert Gemini's response into a Python dictionary.
    """

    if not response_text:

        return None


    text = str(
        response_text
    ).strip()


    # Remove JSON Markdown fences if present.
    text = re.sub(
        r"^```json\s*",
        "",
        text,
        flags=re.IGNORECASE
    )

    text = re.sub(
        r"^```\s*",
        "",
        text
    )

    text = re.sub(
        r"\s*```$",
        "",
        text
    )

    text = text.strip()


    # First attempt: direct JSON parsing.
    try:

        return json.loads(
            text
        )

    except Exception:

        pass


    # Second attempt: find the JSON object.
    start = text.find(
        "{"
    )

    end = text.rfind(
        "}"
    )


    if start == -1 or end == -1:

        return None


    candidate = text[
        start:end + 1
    ]


    try:

        return json.loads(
            candidate
        )

    except Exception:

        return None


