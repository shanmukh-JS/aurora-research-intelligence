# ================================================================
# 7. HELPER — DETECT BAD TITLE
# ================================================================
#
# Your screenshot showed the title field containing:
#
# "Received 5 November 2025..."
#
# This is clearly publication metadata rather than a title.
#
# We detect these cases so the UI can use a safer title fallback.
# ================================================================

def is_bad_title(value):

    if not value:
        return True


    text = str(value).strip()


    metadata_patterns = [

        r"\breceived\b",
        r"\baccepted\b",
        r"\bdate of publication\b",
        r"\bdate of current version\b",
        r"\bpublished\b",
        r"\bdoi\b",
        r"\bvolume\b",
        r"\bissue\b",
        r"\bavailable online\b"

    ]


    matches = sum(

        bool(
            re.search(
                pattern,
                text,
                flags=re.IGNORECASE
            )
        )

        for pattern in metadata_patterns

    )


    # A title normally should not contain multiple
    # publication metadata markers.

    if matches >= 1:

        return True


    # Very long metadata-like strings are unlikely
    # to be a title.

    if len(text) > 250:

        return True


    return False


# ================================================================
# 8. HELPER — FIND UI TITLE FROM FIRST PAGE
# ================================================================
#
# This is a conservative display fallback.
#
# It does NOT overwrite the underlying Cell 3 analysis.
# It only prevents an obviously incorrect title from being
# displayed in the dashboard.
# ================================================================

def find_ui_title_from_first_page():

    pages = AURORA.get(
        "pages",
        []
    )


    if not pages:

        return "Research Paper"


    first_page = pages[0]


    raw_text = first_page.get(
        "text",
        ""
    )


    if not raw_text:

        return "Research Paper"


    lines = [

        re.sub(
            r"\s+",
            " ",
            line
        ).strip()

        for line in raw_text.splitlines()

    ]


    lines = [

        line

        for line in lines

        if line

    ]


    # ------------------------------------------------------------
    # Remove obvious metadata lines.
    # ------------------------------------------------------------

    metadata_regex = re.compile(

        r"(received|accepted|date of publication|"
        r"date of current version|doi:|https?://|"
        r"copyright|published|vol\.|volume|issue)",

        flags=re.IGNORECASE

    )


    candidates = []


    for index, line in enumerate(lines[:40]):

        if metadata_regex.search(line):

            continue


        if len(line) < 8:

            continue


        if len(line) > 180:

            continue


        # Avoid obvious author/contact lines.

        if "@" in line:

            continue


        if re.search(
            r"\b(university|department|institute|college)\b",
            line,
            flags=re.IGNORECASE
        ):

            continue


        candidates.append(
            (
                index,
                line
            )
        )


    if not candidates:

        return "Research Paper"


    # ------------------------------------------------------------
    # Prefer the earliest substantial candidate.
    # ------------------------------------------------------------

    first_index, first_line = candidates[0]


    # ------------------------------------------------------------
    # If the first line is a tiny journal/header label,
    # inspect the next few lines.
    # ------------------------------------------------------------

    selected = []


    for index, line in candidates[:5]:

        if index <= first_index + 5:

            selected.append(line)


    if not selected:

        return first_line


    # ------------------------------------------------------------
    # Try to build a multi-line title.
    #
    # Stop when an author-like or metadata-like line appears.
    # ------------------------------------------------------------

    title_parts = []


    for line in selected:

        if metadata_regex.search(line):

            break


        if re.search(
            r"\b(and|et al\.|department|university|"
            r"email|corresponding author)\b",
            line,
            flags=re.IGNORECASE
        ):

            if title_parts:

                break


        title_parts.append(line)


        if len(title_parts) >= 3:

            break


    title = " ".join(
        title_parts
    ).strip()


    if len(title) < 10:

        return first_line


    return title


