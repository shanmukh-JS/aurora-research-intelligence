# 16. CLEAN GEMINI JSON RESPONSE
# ================================================================
#
# Sometimes an LLM may return JSON surrounded by markdown.
# This function safely extracts the JSON object.
# ================================================================

def parse_gemini_json(response_text):

    if not response_text:

        return None


    text = str(response_text).strip()


    # Remove Markdown JSON fences if present.
    text = re.sub(
        r"^```json\s*",
        "",
        text,
        flags=re.IGNORECASE
    )

    text = re.sub(
        r"^```\s*",
        "",
        text
    )

    text = re.sub(
        r"\s*```$",
        "",
        text
    )

    text = text.strip()


    # First attempt: direct JSON parsing.
    try:

        return json.loads(text)

    except Exception:

        pass


    # Second attempt: locate the outermost JSON object.
    start = text.find("{")
    end = text.rfind("}")

    if start == -1 or end == -1:

        return None

    candidate = text[
        start:end + 1
    ]

    try:

        return json.loads(candidate)

    except Exception:

        return None


