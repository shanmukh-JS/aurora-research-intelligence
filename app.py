# 11. CREATE EVIDENCE CONTEXT
# ================================================================
#
# CELL 5 will use this function to create the evidence
# context that is sent to Gemini.
#
# Each block contains page and evidence information.
# ================================================================

def create_rag_context(
    retrieval_results,
    max_characters=7000
):
    """
    Convert retrieved chunks into grounded context.

    Parameters
    ----------
    retrieval_results : dict
        Output from retrieve_relevant_evidence().

    max_characters : int
        Maximum context length.

    Returns
    -------
    str
        Evidence-grounded context.
    """

    if not retrieval_results:

        return ""


    results = retrieval_results.get(
        "results",
        []
    )


    if not results:

        return ""


    context_parts = []

    current_length = 0


    for index, result in enumerate(
        results,
        start=1
    ):

        text = result.get(
            "text",
            ""
        )

        if not text:

            continue


        page_number = result.get(
            "page_number"
        )

        evidence_id = result.get(
            "evidence_id"
        )

        chunk_id = result.get(
            "chunk_id"
        )

        score = result.get(
            "score",
            0
        )


        evidence_block = f"""
[EVIDENCE {index}]
Source: {result.get("source_id")}
Evidence ID: {evidence_id}
Page: {page_number}
Chunk ID: {chunk_id}
Retrieval Score: {score}

{text}
"""


        # Respect the context limit.
        if (
            current_length
            + len(evidence_block)
            > max_characters
        ):

            break


        context_parts.append(
            evidence_block
        )

        current_length += len(
            evidence_block
        )


    return "\n".join(
        context_parts
    ).strip()


