# 6. EXTRACT LOCAL EVIDENCE
# ================================================================
#
# This function searches the already extracted paper for
# relevant evidence.
#
# It does NOT make an AI claim.
# ================================================================

def collect_intelligence_evidence(
    keywords,
    maximum_pages=5
):
    """
    Collect page-level evidence related to a topic.
    """

    pages = get_extracted_pages()

    if not pages:

        return []


    if isinstance(
        keywords,
        str
    ):

        keywords = [keywords]


    keywords = [

        str(keyword).lower()

        for keyword in keywords

    ]


    evidence = []


    for page in pages:

        text = page.get(
            "text",
            ""
        )


        if not text:

            continue


        lower_text = text.lower()


        matched_keywords = [

            keyword

            for keyword in keywords

            if keyword in lower_text

        ]


        if not matched_keywords:

            continue


        # Create a compact excerpt.
        excerpt = text[:1200]


        evidence.append({

            "source_id": page.get(
                "source_id"
            ),

            "evidence_id": page.get(
                "evidence_id"
            ),

            "page_number": page.get(
                "page_number"
            ),

            "matched_keywords": matched_keywords,

            "excerpt": excerpt

        })


        if len(evidence) >= maximum_pages:

            break


    return evidence


