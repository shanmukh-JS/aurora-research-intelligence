# ================================================================
# 10. RETRIEVE RELEVANT EVIDENCE
# ================================================================
#
# Given a user question, return the most relevant chunks.
#
# Example:
#
# Question:
# "What dataset was used?"
#
#        ↓
#
# Search all chunks
#        ↓
# Score each chunk
#        ↓
# Sort by relevance
#        ↓
# Return top chunks
# ================================================================

def retrieve_relevant_evidence(
    query,
    top_k=RAG_DEFAULT_TOP_K,
    minimum_score=0.05
):
    """
    Retrieve relevant evidence for a query.

    Parameters
    ----------
    query : str
        User question.

    top_k : int
        Maximum number of chunks to return.

    minimum_score : float
        Minimum relevance score.

    Returns
    -------
    dict
        Retrieval results.
    """

    # ------------------------------------------------------------
    # VALIDATE QUERY
    # ------------------------------------------------------------

    if not query or not str(query).strip():

        return {

            "success": False,

            "message": (
                "Please provide a question or search query."
            ),

            "results": []

        }


    query = str(
        query
    ).strip()


    # ------------------------------------------------------------
    # VALIDATE TOP K
    # ------------------------------------------------------------

    try:

        top_k = int(
            top_k
        )

    except Exception:

        top_k = RAG_DEFAULT_TOP_K


    top_k = max(
        1,
        min(
            top_k,
            RAG_MAX_TOP_K
        )
    )


    # ------------------------------------------------------------
    # GET RAG CHUNKS
    # ------------------------------------------------------------

    chunks = AURORA.get(
        "rag",
        {}
    ).get(
        "chunks",
        []
    )


    if not chunks:

        return {

            "success": False,

            "message": (
                "RAG index is empty. "
                "Run build_rag_index() after extracting a PDF."
            ),

            "results": []

        }


    # ------------------------------------------------------------
    # SCORE ALL CHUNKS
    # ------------------------------------------------------------

    scored_results = []


    for chunk in chunks:

        score_information = calculate_rag_score(
            query,
            chunk
        )


        score = score_information[
            "score"
        ]


        if score < minimum_score:

            continue


        # Copy the chunk metadata without modifying
        # the original stored index.
        result = {

            "chunk_id": chunk.get(
                "chunk_id"
            ),

            "source_id": chunk.get(
                "source_id"
            ),

            "page_number": chunk.get(
                "page_number"
            ),

            "evidence_id": chunk.get(
                "evidence_id"
            ),

            "chunk_number": chunk.get(
                "chunk_number"
            ),

            "text": chunk.get(
                "text"
            ),

            "character_count": chunk.get(
                "character_count"
            ),

            "word_count": chunk.get(
                "word_count"
            ),

            "score": score_information[
                "score"
            ],

            "matched_terms": score_information[
                "matched_terms"
            ],

            "match_count": score_information[
                "match_count"
            ],

            "coverage": score_information[
                "coverage"
            ],

            "phrase_match": score_information[
                "phrase_match"
            ]

        }


        scored_results.append(
            result
        )


    # ------------------------------------------------------------
    # SORT BY RELEVANCE
    # ------------------------------------------------------------

    scored_results.sort(

        key=lambda item: (
            item["score"],
            item["coverage"],
            item["match_count"]
        ),

        reverse=True

    )


    # ------------------------------------------------------------
    # RETURN TOP RESULTS
    # ------------------------------------------------------------

    results = scored_results[
        :top_k
    ]


    if not results:

        return {

            "success": True,

            "message": (
                "No sufficiently relevant evidence "
                "was found for this query."
            ),

            "results": []

        }


    return {

        "success": True,

        "message": (
            f"{len(results)} relevant evidence "
            "chunk(s) retrieved."
        ),

        "query": query,

        "results": results

    }


