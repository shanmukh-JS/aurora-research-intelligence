# 12. EXTRACT KEYWORDS LOCALLY
# ================================================================

def local_extract_keywords():

    pages = get_extracted_pages()

    for page in pages:

        text = page_text(page)

        if not text:

            continue

        match = re.search(
            r"(?:keywords?|index terms?)\s*[:\-]\s*(.*)",
            text,
            flags=re.IGNORECASE
        )

        if not match:

            continue

        keyword_text = match.group(1)

        # Stop if the same line contains the beginning of
        # another major section.
        keyword_text = re.split(
            r"\b(?:introduction|1\.)\b",
            keyword_text,
            maxsplit=1,
            flags=re.IGNORECASE
        )[0]

        # Most academic papers separate keywords with commas
        # or semicolons.
        raw_keywords = re.split(
            r"[,;•|]",
            keyword_text
        )

        keywords = []

        for keyword in raw_keywords:

            keyword = keyword.strip()

            if keyword and len(keyword) <= 150:

                keywords.append(keyword)

        # Remove duplicates.
        unique_keywords = []

        for keyword in keywords:

            if keyword.lower() not in [
                item.lower()
                for item in unique_keywords
            ]:

                unique_keywords.append(keyword)

        if unique_keywords:

            evidence = [
                make_evidence_record(
                    page,
                    section="Keywords",
                    excerpt=", ".join(unique_keywords)
                )
            ]

            return unique_keywords, evidence

    return [], []


