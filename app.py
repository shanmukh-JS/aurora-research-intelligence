# ================================================================
# 9. PARSE INTELLIGENCE JSON
# ================================================================

def parse_intelligence_json(
    response_text
):
    """
    Safely parse Gemini's JSON response.
    """

    if not response_text:

        return None


    text = str(
        response_text
    ).strip()


    # Remove Markdown JSON fences.
    text = re.sub(
        r"^```json\s*",
        "",
        text,
        flags=re.IGNORECASE
    )

    text = re.sub(
        r"^```\s*",
        "",
        text
    )

    text = re.sub(
        r"\s*```$",
        "",
        text
    )

    text = text.strip()


    # Direct JSON parsing.
    try:

        return json.loads(
            text
        )

    except Exception:

        pass


    # Search for the outer JSON object.
    start = text.find(
        "{"
    )

    end = text.rfind(
        "}"
    )


    if start == -1 or end == -1:

        return None


    candidate = text[
        start:end + 1
    ]


    try:

        return json.loads(
            candidate
        )

    except Exception:

        return None


# ================================================================
# 10. NORMALIZE INTELLIGENCE
# ================================================================
#
# This prevents malformed Gemini output from breaking
# the AURORA application.
# ================================================================

def normalize_intelligence(
    raw_intelligence
):

    normalized = create_empty_intelligence()


    if not isinstance(
        raw_intelligence,
        dict
    ):

        return normalized


    valid_statuses = {

        "PAPER_STATED",

        "PAPER_EVIDENCE_CANDIDATE",

        "NOT_FOUND",

        "AI_INFERRED",

        "POTENTIAL_GAP_REQUIRES_REVIEW"

    }


    for field_name in INTELLIGENCE_FIELDS:

        field_data = raw_intelligence.get(
            field_name
        )


        if not isinstance(
            field_data,
            dict
        ):

            continue


        items = field_data.get(
            "items",
            []
        )


        status = field_data.get(
            "status",
            "NOT_FOUND"
        )


        evidence = field_data.get(
            "evidence",
            []
        )


        if not isinstance(
            items,
            list
        ):

            items = []


        if not isinstance(
            evidence,
            list
        ):

            evidence = []


        if status not in valid_statuses:

            status = "NOT_FOUND"


        cleaned_items = []


        for item in items[:
            INTELLIGENCE_MAX_ITEMS_PER_SECTION
        ]:

            if not isinstance(
                item,
                dict
            ):

                continue


            statement = item.get(
                "statement"
            )


            if not statement:

                continue


            item_status = item.get(
                "status",
                status
            )


            if item_status not in valid_statuses:

                item_status = status


            item_evidence = item.get(
                "evidence",
                []
            )


            if not isinstance(
                item_evidence,
                list
            ):

                item_evidence = []


            cleaned_items.append({

                "statement": str(
                    statement
                ).strip(),

                "status": item_status,

                "category": item.get(
                    "category"
                ),

                "evidence": item_evidence

            })


        normalized[field_name] = {

            "items": cleaned_items,

            "status": status,

            "evidence": evidence

        }


    return normalized


# ================================================================
# 11. VALIDATE INTELLIGENCE EVIDENCE
# ================================================================
#
# Only evidence that maps to actual extracted pages is retained.
# ================================================================

def validate_intelligence_evidence(
    intelligence
):

    pages = get_extracted_pages()


    valid_evidence_ids = {

        page.get(
            "evidence_id"
        )

        for page in pages

        if page.get(
            "evidence_id"
        )

    }


    valid_page_numbers = {

        page.get(
            "page_number"
        )

        for page in pages

        if page.get(
            "page_number"
        ) is not None

    }


    for field_name in INTELLIGENCE_FIELDS:

        field = intelligence.get(
            field_name,
            {}
        )


        # --------------------------------------------------------
        # FIELD-LEVEL EVIDENCE
        # --------------------------------------------------------

        field_evidence = field.get(
            "evidence",
            []
        )


        valid_field_evidence = []


        for evidence in field_evidence:

            if not isinstance(
                evidence,
                dict
            ):

                continue


            evidence_id = evidence.get(
                "evidence_id"
            )

            page_number = evidence.get(
                "page_number"
            )


            if (
                evidence_id in valid_evidence_ids
                or page_number in valid_page_numbers
            ):

                valid_field_evidence.append(
                    evidence
                )


        field["evidence"] = (
            valid_field_evidence
        )


        # --------------------------------------------------------
        # ITEM-LEVEL EVIDENCE
        # --------------------------------------------------------

        items = field.get(
            "items",
            []
        )


        for item in items:

            item_evidence = item.get(
                "evidence",
                []
            )


            valid_item_evidence = []


            for evidence in item_evidence:

                if not isinstance(
                    evidence,
                    dict
                ):

                    continue


                evidence_id = evidence.get(
                    "evidence_id"
                )

                page_number = evidence.get(
                    "page_number"
                )


                if (
                    evidence_id in valid_evidence_ids
                    or page_number in valid_page_numbers
                ):

                    valid_item_evidence.append(
                        evidence
                    )


            item["evidence"] = (
                valid_item_evidence
            )


    return intelligence


